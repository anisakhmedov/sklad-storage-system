const DICTS: Record<Locale, Dict> = { ru, uz };
const DEFAULT_LOCALE: Locale = "uz";
const LOCALE_STORAGE_KEY = "sklad_miniapp_locale";

function resolve(dict: Dict, path: string): string | undefined {
  let cur: string | Dict = dict;
  for (const part of path.split(".")) {
    if (typeof cur !== "object" || cur === null) return undefined;
    const next: string | Dict | undefined = cur[part];
    if (next === undefined) return undefined;
    cur = next;
  }
  return typeof cur === "string" ? cur : undefined;
}

function interpolate(str: string, vars?: Record<string, string | number>): string {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (match, key) => (vars[key] !== undefined ? String(vars[key]) : match));
}

interface I18nCtx {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const LocaleContext = createContext<I18nCtx | null>(null);

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(DEFAULT_LOCALE);

  useEffect(() => {
    const saved = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    if (saved === "ru" || saved === "uz") setLocaleState(saved);
  }, []);

  function setLocale(l: Locale) {
    setLocaleState(l);
    window.localStorage.setItem(LOCALE_STORAGE_KEY, l);
  }

  const t = useMemo(() => {
    return (key: string, vars?: Record<string, string | number>) => {
      const raw = resolve(DICTS[locale], key) ?? resolve(DICTS.ru, key) ?? key;
      return interpolate(raw, vars);
    };
  }, [locale]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, t]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(LocaleContext);
  if (!ctx) throw new Error("useI18n() must be used within <LocaleProvider>");
  return ctx;
}
